export function step(): Float32Array {
  const noise = seeded(21);
  const thump = osc("sine", sweep([[0, 130], [0.05, 80], [0.1, 55], [0.2, 43]]));
  const level = envelope([[0, 0.4], [0.03, 1.3], [0.09, 1.2], [0.15, 0.7], [0.16, 0.85], [0.22, 0.3], [0.26, 0.15], [0.3, 0.08], [0.47, 0.03], [0.48, 0]]);
  const clank = envelope([[0, 0.45], [0.1, 0.3], [0.2, 0.15], [0.3, 0], [0.48, 0]]);
  const ring = biquad("band", 3300, 3);
  const buzz = biquad("band", 5000, 1.5);
  const tail = envelope([[0, 0], [0.15, 0.1], [0.22, 0.45], [0.3, 0.55], [0.46, 0.45], [0.48, 0]]);
  return render(0.836, (t) => {
    const n = noise();
    return clip(level(t) * (thump(t) - 0.3), 2) + clank(t) * n + tail(t) * (ring(n) + buzz(n));
  });
}


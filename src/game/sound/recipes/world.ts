export function siren(): Float32Array {
  const noise = seeded(32);
  const pitch = sweep([[0, 470], [0.06, 490], [0.12, 520], [0.18, 577], [0.24, 613], [0.3, 657], [0.38, 700], [0.48, 750], [0.6, 785], [0.69, 820], [0.84, 880], [0.9, 850]]);
  const formant = envelope([[0, -14], [400, -14], [1100, -8], [1600, 0], [2400, -6], [3300, -15], [4000, -23], [5500, -30]]);
  const level = envelope([[0, 0.04], [0.115, 0.41], [0.135, 0.28], [0.215, 0.47], [0.225, 0.32], [0.255, 0.49], [0.265, 0.32], [0.275, 0.56], [0.305, 0.71], [0.345, 0.42], [0.465, 0.75], [0.495, 0.44], [0.545, 0.76], [0.585, 0.45], [0.635, 0.72], [0.685, 0.61], [0.695, 0.43], [0.735, 0.65], [0.765, 0.26], [0.785, 0.4], [0.835, 0.19], [0.855, 0.33], [0.895, 0.03], [1.025, 0]]);
  let cycles = 0;
  return render(1.025, (t) => {
    const f0 = pitch(t);
    cycles += f0 / BASE_RATE;
    let tone = 0;
    let power = 0;
    for (let k = 1; k * f0 < 5500; k++) {
      const weight = 10 ** (formant(k * f0) / 20);
      tone += weight * Math.sin(2 * Math.PI * k * cycles);
      power += (weight * weight) / 2;
    }
    return level(t) * (tone / Math.sqrt(power) + 0.25 * noise());
  });
}


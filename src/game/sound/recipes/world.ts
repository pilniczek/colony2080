export function inventory(): Float32Array {
  const noise = seeded(22);
  const hum = onePole(150, "low");
  const partials = [1, 3, 5, 7].map((harmonic) => osc("sine", () => 360 * harmonic));
  const third = envelope([[0, 0], [0.04, 0.2], [0.235, 0.2]]);
  const fifth = envelope([[0, 0.9], [0.04, 0.4], [0.07, 0.1], [0.12, 0.05], [0.15, 0.3], [0.235, 0.3]]);
  const seventh = envelope([[0, 0.5], [0.04, 0.15], [0.07, 0.08], [0.12, 0.05], [0.15, 0.28], [0.235, 0.28]]);
  const level = steps(0.01, [0.22, 0.25, 0.22, 0.22, 0.2, 0.16, 0.12, 0.13, 0.16, 0.22, 0.27, 0.26, 0.24, 0.2, 0.16, 0.27, 0.28, 0.33, 0.4, 0.39, 0.36, 0.32, 0.24]);
  return render(0.235, (t) => {
    const weights = [1, third(t), fifth(t), seventh(t)];
    const power = weights.reduce((sum, w) => sum + w * w, 0) / 2;
    const tone = partials.reduce((sum, partial, k) => sum + weights[k]! * partial(t), 0);
    return t < 0.224 ? (level(t) * tone) / Math.sqrt(power) + 0.25 * hum(noise()) : 0;
  });
}

